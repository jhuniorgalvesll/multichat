  attachReceipt: (id) => ipcRenderer.invoke('ship:attach-receipt', id),
  trackShipment: (id) => ipcRenderer.invoke('ship:track', id),
  setTrackingUrl: (carrier, url) => ipcRenderer.invoke('ship:set-url', carrier, url),
  sendShipment: (id) => ipcRenderer.invoke('ship:send', id),
  pickTemplateImages: () => ipcRenderer.invoke('templates:pick-images'),
  toggleDnd: () => ipcRenderer.send('dnd:toggle'),
  toggleTheme: () => ipcRenderer.send('theme:toggle'),
  copyCreatorYape: () => ipcRenderer.send('coffee:copy'),
  ticketProfiles: () => ipcRenderer.invoke('ticket:profiles'),
  saveTicketProfiles: (list) => ipcRenderer.invoke('ticket:save-profiles', list),
  pickTicketImage: (kind) => ipcRenderer.invoke('ticket:pick-image', kind),
  printTicket: (ticket, options) => ipcRenderer.invoke('ticket:print', ticket, options),
  lastTicketProfile: () => ipcRenderer.invoke('ticket:last-profile'),
  ticketPrinters: () => ipcRenderer.invoke('ticket:printers'),
  ticketToChat: (text) => ipcRenderer.invoke('ticket:to-chat', text),
  formsMenu: () => ipcRenderer.send('forms:menu'),
  getForms: () => ipcRenderer.invoke('forms:get'),
  saveForms: (forms) => ipcRenderer.invoke('forms:save', forms),
  ticketFromSelection: () => ipcRenderer.send('ticket:from-selection'),
  remindersMenu: () => ipcRenderer.send('reminders:menu'),
