  getTemplates: () => ipcRenderer.invoke('templates:get'),
  saveTemplates: (list) => ipcRenderer.invoke('templates:save', list),
  unlock: (password) => ipcRenderer.invoke('lock:unlock', password),
  resetPassword: (answer, password) => ipcRenderer.invoke('lock:reset', answer, password),
  savePassword: (payload) => ipcRenderer.invoke('lock:save', payload),
  setBadgeIcon: (dataUrl, count) => ipcRenderer.send('badge:icon', dataUrl, count),
  onState: (fn) => ipcRenderer.on('state', (_e, state) => fn(state)),
  onStartRename: (fn) => ipcRenderer.on('tab:start-rename', (_e, id) => fn(id)),
  onPasswordDialog: (fn) => ipcRenderer.on('ui:password', (_e, mode) => fn(mode)),
  onTemplatesDialog: (fn) => ipcRenderer.on('ui:templates', () => fn()),
  onNewSale: (fn) => ipcRenderer.on('sale:new', (_e, data) => fn(data)),
  onReminderDialog: (fn) => ipcRenderer.on('ui:reminder', (_e, data) => fn(data)),
  onTrackingUrlDialog: (fn) => ipcRenderer.on('ui:tracking-url', (_e, data) => fn(data)),
  onCoffeeDialog: (fn) => ipcRenderer.on('ui:coffee', () => fn()),
  onNewTicket: (fn) => ipcRenderer.on('ticket:new', (_e, data) => fn(data)),
  onSalesList: (fn) => ipcRenderer.on('ui:sales', () => fn()),
  onShipments: (fn) => ipcRenderer.on('ui:shipments', () => fn()),
  onTicketProfiles: (fn) => ipcRenderer.on('ui:ticket-profiles', () => fn()),
  onFormsDialog: (fn) => ipcRenderer.on('ui:forms', () => fn()),
  onAboutPanel: (fn) => ipcRenderer.on('ui:about', () => fn()),
  onSpeak: (fn) => ipcRenderer.on('ui:speak', (_e, text) => fn(text)),
  about: () => ipcRenderer.invoke('app:about'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  onUpdateState: (fn) => ipcRenderer.on('update:state', (_e, state) => fn(state)),
